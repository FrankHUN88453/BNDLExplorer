"""Regenerate bndlx/knownids.py from tools/hashes.txt.

hashes.txt holds C# `Dictionary<uint|int, string>` initialisers (ResourceTypeNames, Names, EventNames, CarNames,
PackNames, Shaders, Parameters, ...). Add entries there, run `python tools/gen_knownids.py`, done.

  python tools/gen_knownids.py [hashes.txt]
"""
import os
import re
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), 'bndlx', 'knownids.py')


def parse(path):
    t = open(path, encoding='utf-8', errors='replace').read().replace('\r', '')
    heads = [(m.start(), m.group(1)) for m in re.finditer(r'Dictionary<\w+,\s*string>\s+(\w+)', t)]
    tables = []
    for i, (s, nm) in enumerate(heads):
        blk = t[s:heads[i + 1][0] if i + 1 < len(heads) else len(t)]
        d = {}
        for m in re.finditer(r'(?:\{\s*|\[)(0x[0-9A-Fa-f]+|\d+)u?\]?\s*(?:,|=)\s*"((?:[^"\\]|\\.)*)"', blk):
            d[int(m.group(1), 0)] = m.group(2).replace('\\"', '"')
        tables.append((nm, d))
    return tables


def dump(name, d, hexkeys=True):
    lines = [f'{name} = {{']
    for k in sorted(d):
        lines.append(f'    {k:#010x}: {d[k]!r},' if hexkeys else f'    {k}: {d[k]!r},')
    lines.append('}')
    return '\n'.join(lines)


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'hashes.txt')
    tabs = parse(src)
    types = {}
    gc = {}                        # id -> (name, category); first table listed wins
    shaders, params = {}, {}
    order = {'Names': 'id', 'CarNames': 'car', 'EventNames': 'event', 'PackNames': 'pack'}
    for nm, d in tabs:
        if nm == 'ResourceTypeNames':
            types.update(d)
        elif nm == 'Shaders':
            shaders.update(d)
        elif nm == 'Parameters':
            params.update(d)
        elif nm in order:
            for k, v in d.items():
                gc.setdefault(k, (v, order[nm]))
    # the int-keyed `Names` (vehicles, liveries, ...) is the most polished table: it overrides the others
    for nm, d in tabs:
        if nm == 'Names' and any(isinstance(k, int) and k > 100000 and 'Manufacturer' in v for k, v in d.items()):
            for k, v in d.items():
                gc[k] = (v, 'id')
    bad = [(n, h) for h, n in params.items() if (~zlib.crc32(n.encode('latin1'))) & 0xFFFFFFFF != h]
    for n, h in bad:
        print(f'warning: parameter {n!r} does not hash to {h:#x} (~crc32); kept anyway')
    out = ['"""Known ids -> names, generated by tools/gen_knownids.py from tools/hashes.txt. Do not edit by hand."""', '',
           '# resource type ids', dump('RESOURCE_TYPES', types), '',
           '# shader resource ids (low 32 bits)', dump('SHADERS', shaders), '',
           '# material constant name hashes: ~crc32(name)', dump('PARAMETERS', params), '',
           '# Genesys object (GameChanger) ids -> (name, category)', 'GAMECHANGER = {']
    for k in sorted(gc):
        out.append(f'    {k:#010x}: ({gc[k][0]!r}, {gc[k][1]!r}),')
    out += ['}', '']
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out))
    print(f'{len(types)} types, {len(gc)} gamechanger ids, {len(shaders)} shaders, {len(params)} parameters -> {OUT}')


if __name__ == '__main__':
    main()
